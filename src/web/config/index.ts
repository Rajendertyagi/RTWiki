/**
 * Shell layout dimensions. Single source of truth so the AppShell navbar
 * width, the rail column and the collapse toggle all agree.
 *
 * Slice 2 extends this with pane geometry: defaults, minimums, maximums and
 * the divider hit-area. Every resizable boundary reads these values — no
 * scattered widths in CSS or TSX. Minimums also derive the temporary
 * narrow-window collapse threshold (no fixed breakpoint).
 */
// Base primitives for derived composite heights.
// The band and the tab row deliberately share one value: they are the same row.
// A taller band leaves the 40px tab row top-aligned in dead space (measured 9px
// at 50px) while the 46x49 caption buttons fill the full band height, so the
// tabs and the window controls stop lining up.
const TAB_STRIP_HEIGHT = 40

export const LAYOUT = {
  /** Height of the tab strip row, which is also the desktop chrome band. */
  tabStripHeight: TAB_STRIP_HEIGHT,
  /**
   * Height of the desktop chrome band: a single row holding the tab strip and
   * the window controls. The launcher rail and page tree run the full window
   * height beside it, so the band never sits above them.
   */
  chromeBandHeight: TAB_STRIP_HEIGHT,
  /** Narrow launcher/action rail (outermost full-height column). Ultra-compact 40px. */
  railWidth: 48,
  /** Mobile drawer width (base breakpoint); decoupled from the desktop tree pane. */
  mobileDrawerWidth: 280,
  /** Page-tree pane width when expanded (user default; persisted). */
  treePaneWidth: 336,
  /** Page-tree pane drag/resize bounds. */
  treePaneMinWidth: 220,
  treePaneMaxWidth: 520,
  /** Central workspace minimum the narrow-window rule preserves first. */
  workspaceMinWidth: 480,
  /** Rich Note right-sidebar width (user default; persisted). */
  rightSidebarWidth: 260,
  /** Right-sidebar drag/resize bounds. */
  rightSidebarMinWidth: 220,
  rightSidebarMaxWidth: 420,
  /** Pointer hit-area width of pane dividers (visible line is 1px). */
  dividerHitWidth: 6,
  /** Divider keyboard-resize step. */
  dividerStepWidth: 20,
  /**
   * Shared overlay z-index. Every floating layer (menus, popovers, portals,
   * full-screen workspaces) must sit above the AppShell navbar so a
   * collision-shifted dropdown near the left edge can never paint behind
   * the sidebar. Single source of truth; referenced through the
   * --rtwiki-overlay-z-index CSS variable for stylesheet consumers.
   */
  overlayZIndex: 1000,
  /** Global application status-bar height (footer). Matches Trilium StatusBar 28px. */
  statusBarHeight: 28,
  /** Visual-block container size clamps (px). */
  blockMinWidth: 240,
  blockMaxWidth: 1600,
  blockMinHeight: 120,
  blockMaxHeight: 2000
} as const

